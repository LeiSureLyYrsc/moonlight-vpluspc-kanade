// Every case needs an approved root: a fixed local volume that is not the
// volume hosting Windows.  On a CI runner that is the runner's real D: scratch
// volume; locally an operator can point KANADE_IDENTITY_TEST_ROOT at an
// approved tree.  There is deliberately no C: fallback: a test that cannot get
// an approved root SKIPs instead of quietly proving the store works on a path
// the product would refuse.
QString approvedScratchVolume()
{
    // The workflow reserves an isolated D: NTFS root and exports it; accept
    // either name so the lane works with the value the workflow already sets.
    for (const char* variable : { "KANADE_DPAPI_TEST_ROOT", "KANADE_IDENTITY_TEST_ROOT" }) {
        const QByteArray fromEnv = qgetenv(variable);
        if (!fromEnv.isEmpty()) {
            const QString candidate = QString::fromLocal8Bit(fromEnv);
            // The workflow pre-creates the base; a leaf under it is what the
            // store actually owns, so validate the shape the store will see.
            if (Kanade::IdentityTestHooks::rootIsAccepted(candidate + QStringLiteral("/_probe"))) {
                return candidate;
            }
            return QString();
        }
    }
    // Candidate bases, in order.  "D:/a" is where GitHub-hosted Windows runners
    // put the workspace; "_kanade-identity" keeps the scratch beside it.  A
    // candidate is used only when the store would accept a root *under* it, so
    // the decision matches what the store enforces (fixed local non-system
    // volume, no mounted folder), not a guess.
    for (const char* candidate : { "D:/a", "D:", "E:", "F:" }) {
        const QString base = QString::fromLatin1(candidate);
        if (Kanade::IdentityTestHooks::rootIsAccepted(base + QStringLiteral("/_kanade-identity"))) {
            return base + QStringLiteral("/_kanade-identity");
        }
    }
    return QString();
}

// Reserves a unique store root path under the approved volume without creating
// it.  The store itself creates the leaf with its private DACL, which is
// exactly the production path -- a pre-created directory would carry an
// inherited ACL and be (correctly) refused.
class ScratchRoot {
public:
    ScratchRoot() : ScratchRoot(QStringLiteral("kanade-identity"))
    {
    }

    explicit ScratchRoot(const QString& leaf)
    {
        const QString base = approvedScratchVolume();
        if (base.isEmpty()) {
            return;
        }
        // Only the base is created here.  It holds no secret; the leaf below it
        // is created privately by the store.
        if (!QDir().mkpath(base)) {
            return;
        }
        static std::atomic<unsigned> counter{0};
        for (int attempt = 0; attempt < 16; ++attempt) {
            const quint64 token = QRandomGenerator::global()->generate64();
            const QString candidate =
                base + QLatin1Char('/') + leaf + QStringLiteral("-") +
                QString::number(token, 16) + QString::number(counter.fetch_add(1));
            if (!QFileInfo::exists(candidate)) {
                m_path = candidate;
                return;
            }
        }
    }

    ~ScratchRoot()
    {
        if (!m_path.isEmpty()) {
            removeTree(m_path);
        }
    }

    ScratchRoot(const ScratchRoot&) = delete;
    ScratchRoot& operator=(const ScratchRoot&) = delete;

    bool valid() const { return !m_path.isEmpty(); }
    QString path() const { return m_path; }

private:
    static void removeTree(const QString& path)
    {
        QDir dir(path);
        if (!dir.exists()) {
            return;
        }
        // Clear read-only/hidden bits so rmdir cannot fail on our own files.
        const QFileInfoList entries =
            dir.entryInfoList(QDir::Files | QDir::Dirs | QDir::NoDotAndDotDot | QDir::Hidden |
                                  QDir::System,
                              QDir::DirsFirst);
        for (const QFileInfo& entry : entries) {
            if (entry.isDir() && !entry.isSymLink()) {
                removeTree(entry.absoluteFilePath());
            }
            else {
                QFile::setPermissions(entry.absoluteFilePath(),
                                      QFile::ReadOwner | QFile::WriteOwner);
                QFile::remove(entry.absoluteFilePath());
            }
        }
        dir.rmdir(path);
    }

    QString m_path;
};

