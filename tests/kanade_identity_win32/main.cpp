// Lists the trustees of a file's DACL as strings, plus whether inheritance is
// blocked.  Used only to report what the store wrote; no secret is involved.
QStringList daclSummary(const QString& path)
{
    QStringList result;
    PSECURITY_DESCRIPTOR descriptor = nullptr;
    PACL dacl = nullptr;
    const QString native = QDir::toNativeSeparators(path);
    if (GetNamedSecurityInfoW(reinterpret_cast<LPWSTR>(const_cast<ushort*>(native.utf16())),
                              SE_FILE_OBJECT, DACL_SECURITY_INFORMATION, nullptr, nullptr, &dacl,
                              nullptr, &descriptor) != ERROR_SUCCESS) {
        return result;
    }
    if (descriptor != nullptr && dacl != nullptr) {
        SECURITY_DESCRIPTOR_CONTROL control = 0;
        DWORD revision = 0;
        if (GetSecurityDescriptorControl(descriptor, &control, &revision) &&
            (control & SE_DACL_PROTECTED)) {
            result << QStringLiteral("protected");
        }
        for (DWORD i = 0; i < dacl->AceCount; ++i) {
            LPVOID ace = nullptr;
            if (!GetAce(dacl, i, &ace) || ace == nullptr) {
                break;
            }
            const auto* header = static_cast<const ACE_HEADER*>(ace);
            if (header->AceType != ACCESS_ALLOWED_ACE_TYPE) {
                result << QStringLiteral("ace-type-%1").arg(header->AceType);
                continue;
            }
            const auto* allowed = static_cast<const ACCESS_ALLOWED_ACE*>(ace);
            PSID trustee = const_cast<PSID>(static_cast<const void*>(&allowed->SidStart));
            wchar_t name[256] = {};
            wchar_t domain[256] = {};
            DWORD nameLen = 256;
            DWORD domainLen = 256;
            SID_NAME_USE use = SidTypeUnknown;
            if (LookupAccountSidW(nullptr, trustee, name, &nameLen, domain, &domainLen, &use)) {
                result << QString::fromWCharArray(name);
            }
            else {
                result << QStringLiteral("sid-unresolved");
            }
        }
    }
    if (descriptor != nullptr) {
        LocalFree(descriptor);
    }
    return result;
}

// Attempts to replace a directory with a junction to another directory.
// Returns false when the platform refuses (Developer Mode / privilege), in
// which case the reparse case reports SKIP rather than passing silently.
bool createJunction(const QString& link, const QString& target)
{
    if (!QDir().mkpath(link)) {
        return false;
    }
    // A junction must point at an existing directory and the link directory
    // must be empty; fsutil accepts exactly that.
    QProcess process;
    process.setProgram(QStringLiteral("cmd.exe"));
    process.setArguments({QStringLiteral("/c"),
                          QStringLiteral("fsutil reparsepoint create \"%1\" \"%2\"")
                              .arg(QDir::toNativeSeparators(link),
                                   QDir::toNativeSeparators(target))});
    process.start();
    if (!process.waitForFinished(20000)) {
        process.kill();
        return false;
    }
    return process.exitStatus() == QProcess::NormalExit && process.exitCode() == 0;
}

bool removeJunction(const QString& link)
{
    QProcess process;
    process.setProgram(QStringLiteral("cmd.exe"));
    process.setArguments(
        {QStringLiteral("/c"), QStringLiteral("fsutil reparsepoint delete \"%1\"")
                                   .arg(QDir::toNativeSeparators(link))});
    process.start();
    if (!process.waitForFinished(20000)) {
        process.kill();
        return false;
    }
    const bool ok = process.exitStatus() == QProcess::NormalExit && process.exitCode() == 0;
    QDir().rmdir(link);
    return ok;
}
