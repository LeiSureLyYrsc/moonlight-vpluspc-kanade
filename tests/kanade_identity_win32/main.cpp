void KanadeIdentityWin32Test::pinnedRootBlocksRename()
{
    // Direct evidence that the pin holds: while a save() is between creating
    // the private leaf and installing the file, an outside attempt to rename
    // the pinned root must fail.  We cannot interleave inside save(), so we
    // observe the property at the API level: a rename of a directory that is
    // open without FILE_SHARE_DELETE fails with ERROR_SHARING_VIOLATION.
    //
    // This is a platform-contract test (it validates the assumption the store
    // depends on).  If it ever passed while the store denied sharing, the
    // store's guarantee would be void.
    ScratchRoot dir;
    KANADE_REQUIRE_SCRATCH(dir);

    const QString root = dir.path() + QStringLiteral("/pinned");
    QVERIFY(QDir().mkpath(root));

    HANDLE pinned = CreateFileW(
        reinterpret_cast<LPCWSTR>(QDir::toNativeSeparators(root).utf16()),
        FILE_LIST_DIRECTORY | FILE_READ_ATTRIBUTES | SYNCHRONIZE,
        FILE_SHARE_READ | FILE_SHARE_WRITE, // exactly kPinDirectoryShare
        nullptr, OPEN_EXISTING,
        FILE_FLAG_BACKUP_SEMANTICS | FILE_FLAG_OPEN_REPARSE_POINT, nullptr);
    QVERIFY2(pinned != INVALID_HANDLE_VALUE, "could not open the pin fixture");

    const QString moved = dir.path() + QStringLiteral("/moved");
    const BOOL renamed =
        MoveFileExW(reinterpret_cast<LPCWSTR>(QDir::toNativeSeparators(root).utf16()),
                    reinterpret_cast<LPCWSTR>(QDir::toNativeSeparators(moved).utf16()),
                    MOVEFILE_COPY_ALLOWED);
    const DWORD renameError = GetLastError();
    CloseHandle(pinned);

    QVERIFY2(renamed == FALSE && renameError == ERROR_SHARING_VIOLATION,
             qPrintable(QStringLiteral("rename of an open-no-delete directory must fail with "
                                       "ERROR_SHARING_VIOLATION, got %1")
                            .arg(renameError)));
    QVERIFY(QFileInfo::exists(root));

    // And once released, the rename is possible again (the pin, not the ACL,
    // is what blocked it), so a stale handle cannot wedge the directory.
    QVERIFY(QDir().rename(root, moved));
    QVERIFY(QFileInfo::exists(moved));
}

void KanadeIdentityWin32Test::rootOnSystemVolumeIsRejected()
{
    // The store refuses the volume that HOSTS WINDOWS, decided by volume GUID
    // rather than a hardcoded drive letter.  Derive the system volume from the
    // system directory so this is correct wherever Windows is installed.
    wchar_t systemDirectory[MAX_PATH] = {};
    QVERIFY(GetSystemDirectoryW(systemDirectory, MAX_PATH) != 0);
    const QString systemVolumeRoot = QString::fromWCharArray(systemDirectory, 3);
    const QString systemCandidate = systemVolumeRoot + QStringLiteral("kanade-refused-root");

    QVERIFY2(!Kanade::IdentityTestHooks::rootIsAccepted(systemCandidate),
             "the volume hosting Windows must be refused by GUID");

    // A store pointed there refuses without creating anything.
    Kanade::IdentityStore store(systemCandidate);
    QVERIFY(!store.save(serviceOrigin(), kUserId, enrolled()));
    QVERIFY(!QFileInfo::exists(systemCandidate));

    // The Windows directory is refused too, on whatever volume it lives.
    const QString windowsPath =
        QDir::cleanPath(QString::fromWCharArray(systemDirectory)).section(QLatin1Char('/'), 0, -3);
    if (!windowsPath.isEmpty()) {
        QVERIFY(!Kanade::IdentityTestHooks::rootIsAccepted(windowsPath));
        QVERIFY(!Kanade::IdentityTestHooks::rootIsAccepted(windowsPath +
                                                          QStringLiteral("/kanade-root")));
    }

    // Conversely, the approved scratch volume (which is NOT the system volume)
    // must be accepted: this is what makes the refusal above a GUID comparison
    // rather than a blanket rejection.
    const QString approved = approvedScratchVolume();
    if (!approved.isEmpty()) {
        QVERIFY2(Kanade::IdentityTestHooks::rootIsAccepted(approved + QStringLiteral("/probe")),
                 "the approved non-system volume must be accepted");
    }
}

void KanadeIdentityWin32Test::concurrentSavesNeverCorrupt()
{
    ScratchRoot dir;
    KANADE_REQUIRE_SCRATCH(dir);
    Kanade::IdentityStore store(dir.path());

    // Many concurrent writers to the same scope: every save must either fully
    // succeed or fail; afterwards exactly one complete, loadable envelope is
    // present and it matches one of the seeds that were written.
    //
    // The store is atomic per rename but does NOT serialize writers against
    // each other -- the controller does that with a single-thread pool.  A
    // losing writer may therefore fail or be overwritten by a later one; what
    // must never happen is a torn or fabricated envelope.
    QList<Kanade::InstallationIdentity> identities;
    QList<bool> results;
    const int count = 12;
    for (int i = 0; i < count; ++i) {
        Kanade::InstallationIdentity identity = Kanade::generateIdentity();
        identity.installationId = kInstallationId;
        identities.append(identity);
    }

    QList<QFuture<bool>> futures;
    for (int i = 0; i < count; ++i) {
        const Kanade::InstallationIdentity identity = identities.at(i);
        futures.append(QtConcurrent::run([&store, identity]() {
            return store.save(serviceOrigin(), kUserId, identity);
        }));
    }
    for (QFuture<bool>& future : futures) {
        future.waitForFinished();
        results.append(future.result());
    }

    int succeeded = 0;
    for (bool ok : results) {
        if (ok) {
            ++succeeded;
        }
    }
    QVERIFY(succeeded >= 1);

    Kanade::InstallationIdentity loaded;
    QCOMPARE(store.loadResult(serviceOrigin(), kUserId, loaded),
             Kanade::IdentityStore::LoadResult::Ok);
    bool matched = false;
    for (const Kanade::InstallationIdentity& identity : identities) {
        if (identity.privateKey == loaded.privateKey) {
            matched = true;
            break;
        }
    }
    QVERIFY2(matched, "loaded identity is not any identity that was written");

    // No staging files left behind.
    const QFileInfoList entries =
        QDir(dir.path()).entryInfoList(QDir::Files | QDir::Hidden | QDir::System);
    for (const QFileInfo& entry : entries) {
        QVERIFY2(!entry.fileName().contains(QStringLiteral(".tmp-")),
                 qPrintable(entry.fileName()));
    }
}

void KanadeIdentityWin32Test::concurrentSaveAndLoad()
{
    ScratchRoot dir;
    KANADE_REQUIRE_SCRATCH(dir);
    Kanade::IdentityStore store(dir.path());
    Kanade::InstallationIdentity identity = enrolled();
    QVERIFY(store.save(serviceOrigin(), kUserId, identity));

    std::atomic<bool> stop{false};
    std::atomic<int> okLoads{0};
    std::atomic<int> corruptLoads{0};

    QFuture<void> reader = QtConcurrent::run([&store, &stop, &okLoads, &corruptLoads]() {
        while (!stop.load()) {
            Kanade::InstallationIdentity loaded;
            switch (store.loadResult(serviceOrigin(), kUserId, loaded)) {
            case Kanade::IdentityStore::LoadResult::Ok:
                // Whatever a concurrent writer installed must still be a
                // complete, self-consistent identity.
                if (loaded.privateKey.isEmpty() || loaded.publicKey.isEmpty()) {
                    corruptLoads.fetch_add(1);
                }
                else {
                    okLoads.fetch_add(1);
                }
                break;
            case Kanade::IdentityStore::LoadResult::NotFound:
                // A rename-based replace is atomic, but the name can be absent
                // for an instant if the process observes it between
                // dispositions; that is not corruption.
                break;
            case Kanade::IdentityStore::LoadResult::Error:
            case Kanade::IdentityStore::LoadResult::Unsupported:
            default:
                corruptLoads.fetch_add(1);
                break;
            }
        }
    });

    for (int i = 0; i < 10; ++i) {
        identity = Kanade::generateIdentity();
        identity.installationId = kInstallationId;
        QVERIFY(store.save(serviceOrigin(), kUserId, identity));
    }
    stop.store(true);
    reader.waitForFinished();

    // A load concurrent with an atomic replace must never observe a torn,
    // reparse-redirected or ACL-broken file: those are the only outcomes that
    // map to Error.  Every observed envelope was complete.
    QCOMPARE(corruptLoads.load(), 0);
    QVERIFY(okLoads.load() > 0);
}

void KanadeIdentityWin32Test::concurrentForgetAndSave()
{
    ScratchRoot dir;
    KANADE_REQUIRE_SCRATCH(dir);
    Kanade::IdentityStore store(dir.path());

    for (int i = 0; i < 6; ++i) {
        QFuture<bool> saver = QtConcurrent::run([&store]() {
            Kanade::InstallationIdentity identity = Kanade::generateIdentity();
            identity.installationId = kInstallationId;
            return store.save(serviceOrigin(), kUserId, identity);
        });
        QFuture<bool> forgetter =
            QtConcurrent::run([&store]() { return store.forget(serviceOrigin(), kUserId); });
        saver.waitForFinished();
        forgetter.waitForFinished();
    }

    // Whatever the interleaving, the store must still be loadable or empty --
    // never corrupt.
    Kanade::InstallationIdentity loaded;
    const auto outcome = store.loadResult(serviceOrigin(), kUserId, loaded);
    QVERIFY(outcome == Kanade::IdentityStore::LoadResult::Ok ||
            outcome == Kanade::IdentityStore::LoadResult::NotFound);

    // And a clean save after the storm works.
    QVERIFY(store.save(serviceOrigin(), kUserId, enrolled()));
    QCOMPARE(store.loadResult(serviceOrigin(), kUserId, loaded),
             Kanade::IdentityStore::LoadResult::Ok);
}

void KanadeIdentityWin32Test::invalidScopesAreRejected()
{
    ScratchRoot dir;
    KANADE_REQUIRE_SCRATCH(dir);
    Kanade::IdentityStore store(dir.path());
    const Kanade::InstallationIdentity identity = enrolled();

    QUrl http = serviceOrigin();
    http.setScheme(QStringLiteral("http"));
    QVERIFY(!store.save(http, kUserId, identity));
    QVERIFY(!store.forget(http, kUserId));

    QUrl withPath = serviceOrigin();
    withPath.setPath(QStringLiteral("/v1"));
    QVERIFY(!store.save(withPath, kUserId, identity));

    QUrl ipv6;
    ipv6.setScheme(QStringLiteral("https"));
    ipv6.setHost(QStringLiteral("[::1]"));
    QVERIFY(!store.save(ipv6, kUserId, identity));

    QVERIFY(!store.save(serviceOrigin(), QString(), identity));
    QVERIFY(!store.forget(serviceOrigin(), QString()));

    // A keypair mismatch and an invalid installation id never persist.
    Kanade::InstallationIdentity broken = identity;
    broken.publicKey = Kanade::generateIdentity().publicKey;
    QVERIFY(!store.save(serviceOrigin(), kUserId, broken));

    Kanade::InstallationIdentity badId = identity;
    badId.installationId = QStringLiteral("NOT-A-UUID");
    QVERIFY(!store.save(serviceOrigin(), kUserId, badId));

    Kanade::InstallationIdentity badPending = identity;
    badPending.installationId.clear();
    QVERIFY(store.save(serviceOrigin(), kUserId, badPending));
    Kanade::InstallationIdentity pendingLoaded;
    QCOMPARE(store.loadResult(serviceOrigin(), kUserId, pendingLoaded),
             Kanade::IdentityStore::LoadResult::Ok);
    QVERIFY(pendingLoaded.installationId.isEmpty());
}

void KanadeIdentityWin32Test::printCrossUserCommand()
{
    // Cross-user isolation cannot be proven inside one process.  This slot
    // prints the exact two-account procedure so a CI job or an operator can run
    // it on a runner: account A writes a store, account B must fail closed.
    const QString binary = QCoreApplication::applicationFilePath();
    std::fprintf(stderr,
                 "cross-user isolation (run on a Windows runner with two local accounts)\n"
                 "  1. as account A: run this binary with %%KANADE_IDENTITY_DUMP_ROOT unset\n"
                 "     and KANADE_IDENTITY_WRITE_ROOT=<root> to create a store\n"
                 "  2. as account B: %s dumpState\n"
                 "     with KANADE_IDENTITY_DUMP_ROOT=<root>\n"
                 "  3. expected as B: root_accepted=0 or root_private=0, and\n"
                 "     load_outcome=%d (Error), never 0 (Ok) and never 1 (NotFound)\n",
                 qPrintable(binary), static_cast<int>(Kanade::IdentityStore::LoadResult::Error));

    const QByteArray writeRoot = qgetenv("KANADE_IDENTITY_WRITE_ROOT");
    if (writeRoot.isEmpty()) {
        QSKIP("Set KANADE_IDENTITY_WRITE_ROOT to create a store for the other account");
    }
    Kanade::IdentityStore store(QString::fromLocal8Bit(writeRoot));
    Kanade::InstallationIdentity identity = Kanade::generateIdentity();
    identity.installationId = kInstallationId;
    QVERIFY(store.save(serviceOrigin(), kUserId, identity));
    std::fprintf(stderr, "wrote scope for user=%s under %s\n", qPrintable(kUserId),
                 writeRoot.constData());
}

void KanadeIdentityWin32Test::dumpState()
{
    // Cross-user affordance: point KANADE_IDENTITY_DUMP_ROOT at a store root
    // written by another account and run this test binary with
    // "-functions" filtering to dumpState().  It reports why each scope fails
    // to load without exposing any key material.
    const QByteArray root = qgetenv("KANADE_IDENTITY_DUMP_ROOT");
    if (root.isEmpty()) {
        QSKIP("Set KANADE_IDENTITY_DUMP_ROOT to inspect an existing store root");
    }
    const QString path = QString::fromLocal8Bit(root);
    if (!QFileInfo(path).isDir()) {
        QSKIP("KANADE_IDENTITY_DUMP_ROOT is not a directory");
    }

    std::fprintf(stderr, "root=%s\n", qPrintable(path));
    std::fprintf(stderr, "root_accepted=%d root_private=%d root_plain=%d\n",
                 Kanade::IdentityTestHooks::rootIsAccepted(path) ? 1 : 0,
                 Kanade::IdentityTestHooks::aclIsPrivate(path, true) ? 1 : 0,
                 Kanade::IdentityTestHooks::objectIsPlain(path, true) ? 1 : 0);

    const QFileInfoList entries =
        QDir(path).entryInfoList(QDir::Files | QDir::Hidden | QDir::System);
    for (const QFileInfo& entry : entries) {
        std::fprintf(stderr, "entry=%s private=%d plain=%d\n",
                     qPrintable(entry.fileName()),
                     Kanade::IdentityTestHooks::aclIsPrivate(entry.absoluteFilePath(), false) ? 1
                                                                                            : 0,
                     Kanade::IdentityTestHooks::objectIsPlain(entry.absoluteFilePath(), false) ? 1
                                                                                               : 0);
    }

    // Under a second account the DACL denies access; the load must fail closed
    // rather than report NotFound (which would mint a new key).
    Kanade::IdentityStore store(path);
    Kanade::InstallationIdentity loaded;
    const auto outcome = store.loadResult(serviceOrigin(), kUserId, loaded);
    std::fprintf(stderr, "load_outcome=%d\n", static_cast<int>(outcome));
    QVERIFY(outcome != Kanade::IdentityStore::LoadResult::Ok ||
            !loaded.privateKey.isEmpty());
}

