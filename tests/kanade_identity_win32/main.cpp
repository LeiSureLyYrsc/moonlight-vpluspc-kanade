// Windows storage acceptance tests for the Kanade client installation identity.
//
// Scope: the REAL Win32 store -- DPAPI current-user sealing, the private
// current-user + SYSTEM DACL, handle-pinned reparse-point rejection, atomic
// replace, forget, scope/account isolation and concurrent access.  This target
// is Windows-only and is never part of a non-Windows build.
//
// Safety properties of the test itself:
//   * Every root is a private scratch directory on an APPROVED volume: a fixed
//     local volume that is not the one hosting Windows (the runner's real D:
//     provisioned by the workflow, or KANADE_IDENTITY_TEST_ROOT).  There is no
//     C: fallback -- when no approved volume exists the case SKIPs, so it can
//     never "pass" by proving the store works on a path the product refuses.
//   * Identities are synthetic throwaways generated by the module under test.
//   * No network, no TLS material, no Kanade service, no OS trust store.
//   * No secret is printed: assertions compare booleans and lengths, and a
//     failure message never includes key material.
//
// Cross-user verification (a second Windows account reading the file and
// failing to unseal it) cannot be done in-process.  Two affordances exist:
//   1. dumpState() records, for an existing store root, the DACL trustees and
//      whether the current user can load each scope.  A second account running
//      this test binary against the same root observes load failures.
//   2. crossUserCommand() prints the exact command an operator runs from the
//      other account; see tests/kanade_identity_win32/README.md.
// Both are gated behind explicit flags so the default run stays self-contained.

