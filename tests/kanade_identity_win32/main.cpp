void KanadeIdentityWin32Test::rootReplacedInPlaceIsRejected(){
    // Swap the approved root for a junction to a different directory BETWEEN
    // two store operations.  Each operation must re-prove the root, so the
    // second one fails closed instead of following the new target.
    ScratchRoot dir;
    KANADE_REQUIRE_SCRATCH(dir);
    const QString root = dir.path() + QStringLiteral("/approved-root");
    const QString decoy = dir.path() + QStringLiteral("/decoy");
    QVERIFY(QDir().mkpath(decoy));

    Kanade::IdentityStore store(root);
    Kanade::InstallationIdentity identity = enrolled();
    QVERIFY(store.save(serviceOrigin(), kUserId, identity));
    QVERIFY(Kanade::IdentityTestHooks::aclIsPrivate(root, /*directory=*/true));

    // Rename the real root away and substitute a junction at the same path.
    QVERIFY(QDir().rename(root, root + QStringLiteral("-moved")));
    if (!createJunction(root, decoy)) {
        QDir().rename(root + QStringLiteral("-moved"), root);
        QSKIP("Cannot create a junction (needs fsutil and a NTFS volume)");
    }

    Kanade::InstallationIdentity loaded;
    const auto afterSwap = store.loadResult(serviceOrigin(), kUserId, loaded);
    QVERIFY2(afterSwap == Kanade::IdentityStore::LoadResult::Error,
             "a junction substituted at the approved root must fail closed");
    QVERIFY(!store.save(serviceOrigin(), kUserId, identity));
    QVERIFY(!store.forget(serviceOrigin(), kUserId));

    // Nothing followed the junction into the decoy directory.
    QVERIFY(QDir(decoy).entryList(QDir::Files | QDir::Hidden | QDir::System).isEmpty());

    QVERIFY(removeJunction(root));
    QVERIFY(QDir().rename(root + QStringLiteral("-moved"), root));
    QCOMPARE(store.loadResult(serviceOrigin(), kUserId, loaded),
             Kanade::IdentityStore::LoadResult::Ok);
}

