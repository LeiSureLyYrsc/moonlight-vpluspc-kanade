// assertion: a missing approved volume is unverified, not green.
#define KANADE_REQUIRE_SCRATCH(root)                                                       \
    do {                                                                                   \
        if (!(root).valid()) {                                                             \
            QSKIP("No approved non-system fixed volume for the store root (set "            \
                  "KANADE_IDENTITY_TEST_ROOT or provision the runner D: scratch)");        \
        }                                                                                  \
    } while (false)

